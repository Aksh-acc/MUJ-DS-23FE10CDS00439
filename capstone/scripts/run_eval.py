"""Run the evaluation suite and write results to docs/results.md.

    python scripts/run_eval.py
    python scripts/run_eval.py --sample 60     # faster known-item sample
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from branched_rag import logging_setup
from branched_rag.config import load_config
from branched_rag.evaluation import (
    compare_flat_and_branched,
    evaluate_retrieval,
    evaluate_router,
    load_eval_queries,
    router_errors,
)
from branched_rag.pipeline import BranchedRAGPipeline


def section(title: str, frame, note: str = "") -> str:
    body = frame.to_markdown(index=False) if len(frame) else "_no rows_"
    out = f"\n## {title}\n\n"
    if note:
        out += f"{note}\n\n"
    return out + body + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None)
    parser.add_argument("--sample", type=int, default=120,
                        help="documents per branch for known-item retrieval")
    parser.add_argument("--k", type=int, default=10, help="cutoff for rank metrics")
    args = parser.parse_args()

    logging_setup.configure()
    config = load_config(args.config)
    pipeline = BranchedRAGPipeline.load(args.config)
    queries = load_eval_queries(config.paths.eval_queries)

    print(f"loaded {len(queries)} labelled queries")

    router_table = evaluate_router(pipeline, queries)
    errors = router_errors(pipeline, queries)
    retrieval_table = evaluate_retrieval(pipeline, sample_size=args.sample, k=args.k)
    flat_detail, flat_summary = compare_flat_and_branched(pipeline, queries)

    print("\n== ROUTING ==");   print(router_table.to_string(index=False))
    print("\n== RETRIEVAL =="); print(retrieval_table.to_string(index=False))
    print("\n== FLAT vs BRANCHED =="); print(flat_summary.to_string(index=False))
    if len(errors):
        print("\n== ROUTING ERRORS =="); print(errors.to_string(index=False))

    report = f"""# Evaluation results

Generated by `scripts/run_eval.py` on {date.today().isoformat()}.
Corpus: {pipeline.store.total_chunks} chunks across {len(pipeline.store.names)} branches.
Embedding model: `{config.embedding.model}`. Generation: `{pipeline.llm.description}`.

All numbers below are reproducible from a clean checkout by running
`build_corpus.py`, `build_index.py`, then `run_eval.py`.
"""
    report += section(
        "Routing accuracy",
        router_table,
        "Labels in `data/eval/queries.jsonl` record which sources a question "
        "*should* consult, judged from its wording and independently of what the "
        "router does. `exact_match` is the share of queries whose branch set was "
        "exactly right; `f1` gives partial credit on multi-source questions.",
    )
    report += section(
        "Known-item retrieval",
        retrieval_table,
        f"Document titles as queries, the document's own chunks as the relevant "
        f"set, cutoff k={args.k}, {args.sample} documents sampled per branch. "
        "No human judgements are involved, so this is reproducible exactly.",
    )
    report += section(
        "Branched versus flat index",
        flat_summary,
        "Both systems use identical embeddings, identical BM25, identical RRF and "
        "the same evidence budget per query; only the partitioning differs. "
        "`flat_top_branch_share` is the fraction of the flat system's evidence "
        "coming from its single most-represented branch.",
    )
    if len(errors):
        report += section("Routing errors (hybrid strategy)", errors)
    report += section("Per-query flat/branched detail", flat_detail)

    out = Path(__file__).resolve().parents[1] / "docs" / "results.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
